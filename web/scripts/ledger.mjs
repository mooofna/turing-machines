// Generates the facts ledger and the bibliography as TypeScript modules from the research data.
//
//   src/content/research/facts.json    ->  src/lib/content/facts.ts
//   src/content/research/tables.json   ->  src/lib/content/facts.ts (tables built from facts)
//   src/content/research/sources.json  ->  src/lib/content/sources.ts
//
// The JSON files are the record of the fact check; the TypeScript modules are what the site
// imports. Run `node scripts/ledger.mjs` after editing the JSON files and commit both. The script
// fails on duplicate ids, on facts without a known source, on table rows without a known fact and
// on numbers that JavaScript cannot represent exactly.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const research = join(web, 'src/content/research');
const out = join(web, 'src/lib/content');

/** Date of the fact check that produced the research files. */
const CHECKED = '2026-10-14';

/**
 * @typedef {{ id: string, value: string | number, display: string, source: string[],
 *   url?: string, verified: boolean, note?: string }} ResearchFact
 * @typedef {{ id: string, authors: string, title: string, venue: string, year: number,
 *   url?: string, doi?: string, arxiv?: string, volume?: string, issue?: string,
 *   pages?: string, revision?: number, note?: string, verified: boolean }} ResearchSource
 * @typedef {{ id: string, caption: string, columns: string[],
 *   rows: { fact: string, cells: string[] }[], note?: string }} ResearchTable
 */

/** @param {string} name */
const read = (name) => JSON.parse(readFileSync(join(research, name), 'utf8'));
/** @type {ResearchFact[]} */
const facts = read('facts.json');
/** @type {ResearchSource[]} */
const sources = read('sources.json');
/** @type {ResearchTable[]} */
const tables = read('tables.json');

/** @type {string[]} */
const errors = [];
/**
 * @param {{ id: string }[]} items
 * @param {string} kind
 */
const unique = (items, kind) => {
  const seen = new Set();
  for (const { id } of items) {
    if (seen.has(id)) errors.push(`duplicate ${kind} id ${id}`);
    seen.add(id);
  }
  return seen;
};
const sourceIds = unique(sources, 'source');
const factIds = unique(facts, 'fact');
unique(tables, 'table');

for (const f of facts) {
  if (!Array.isArray(f.source) || f.source.length === 0) errors.push(`fact ${f.id} has no source`);
  for (const s of f.source ?? []) {
    if (!sourceIds.has(s)) errors.push(`fact ${f.id} cites unknown source ${s}`);
  }
  if (typeof f.verified !== 'boolean') errors.push(`fact ${f.id} has no verified flag`);
  if (typeof f.value === 'number' && !Number.isSafeInteger(f.value)) {
    errors.push(`fact ${f.id} has a value that is not a safe integer`);
  }
}
for (const t of tables) {
  if (factIds.has(t.id)) errors.push(`id ${t.id} is both a fact and a table`);
  for (const row of t.rows) {
    if (!factIds.has(row.fact)) errors.push(`table ${t.id} uses unknown fact ${row.fact}`);
    if (row.cells.length !== t.columns.length - 1) {
      errors.push(`table ${t.id}, row ${row.fact}: expected ${t.columns.length - 1} cells`);
    }
  }
}
if (errors.length > 0) {
  console.error(errors.join('\n'));
  process.exit(1);
}

/**
 * @param {Record<string, unknown>} object
 * @param {string[]} keys
 */
const pick = (object, keys) =>
  Object.fromEntries(keys.filter((k) => object[k] !== undefined).map((k) => [k, object[k]]));

/** @type {[string, object][]} */
const factEntries = facts.map((f) => [
  f.id,
  {
    ...pick(f, ['id', 'value', 'display', 'source', 'url']),
    verified: CHECKED,
    confirmed: f.verified,
    ...pick(f, ['note'])
  }
]);

/**
 * "A; B; C" in the research file becomes "A, B and C".
 * @param {string} list
 */
const authors = (list) => {
  const names = list.split(';').map((n) => n.trim());
  return names.length < 2 ? names.join('') : `${names.slice(0, -1).join(', ')} and ${names.at(-1)}`;
};

const sourceEntries = sources.map((s) => ({
  ...pick(s, ['id']),
  authors: authors(s.authors),
  ...pick(s, ['title', 'venue', 'year', 'url', 'doi', 'arxiv']),
  ...pick(s, ['volume', 'issue', 'pages', 'revision', 'note']),
  confirmed: s.verified
}));

/** @param {unknown} value */
const json = (value) => JSON.stringify(value, null, 2);
/** @param {string} from */
const header = (from) =>
  `// Generated by scripts/ledger.mjs from ${from}.\n` +
  `// Do not edit by hand: change the JSON and run \`node scripts/ledger.mjs\`.\n\n`;

const factsTs =
  header('src/content/research/{facts,tables}.json') +
  `import type { Fact } from './types.ts';

/** Date of the fact check behind every entry. */
export const CHECKED = ${json(CHECKED)};

/**
 * A ledger entry. \`verified\` is the date of the fact check; \`confirmed\` says whether the check
 * confirmed the value. An unconfirmed fact may only appear with the qualifying wording that
 * \`render.server.ts\` requires for it.
 */
export interface LedgerFact extends Fact {
  confirmed: boolean;
}

/** A table whose first column is a fact and whose other columns are plain text. */
export interface LedgerTable {
  id: string;
  caption: string;
  columns: string[];
  rows: { fact: string; cells: string[] }[];
  note?: string;
}

export const facts = {
${factEntries.map(([id, f]) => `  ${json(id)}: ${json(f)}`).join(',\n')}
} satisfies Record<string, LedgerFact>;

export type FactId = keyof typeof facts;

export const tables = {
${tables.map((t) => `  ${json(t.id)}: ${json(t)}`).join(',\n')}
} satisfies Record<string, LedgerTable>;

/** The fact with \`id\`, if any. */
export function factById(id: string): LedgerFact | undefined {
  return Object.hasOwn(facts, id) ? (facts as Record<string, LedgerFact>)[id] : undefined;
}

/** The table with \`id\`, if any. */
export function tableById(id: string): LedgerTable | undefined {
  return Object.hasOwn(tables, id) ? (tables as Record<string, LedgerTable>)[id] : undefined;
}
`;

const sourcesTs =
  header('src/content/research/sources.json') +
  `import type { Source } from './types.ts';

/** A bibliography entry with the details the fact check recorded. */
export interface LedgerSource extends Source {
  volume?: string;
  issue?: string;
  pages?: string;
  /** Revision of a wiki page, if the entry cites one. */
  revision?: number;
  note?: string;
  /** Whether the fact check could open the work and confirm the bibliographic data. */
  confirmed: boolean;
}

export const sources: readonly LedgerSource[] = ${json(sourceEntries)};

const byId = new Map(sources.map((s) => [s.id, s]));

/** The source with \`id\`, if any. */
export function sourceById(id: string): LedgerSource | undefined {
  return byId.get(id);
}
`;

const options = { ...(await resolveConfig(join(out, 'facts.ts'))), parser: 'typescript' };
writeFileSync(join(out, 'facts.ts'), await format(factsTs, options));
writeFileSync(join(out, 'sources.ts'), await format(sourcesTs, options));
console.log(
  `facts.ts: ${facts.length} facts, ${tables.length} tables; sources.ts: ${sources.length} sources`
);
